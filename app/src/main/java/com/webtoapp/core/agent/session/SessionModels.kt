package com.webtoapp.core.agent.session

import java.util.UUID

data class AgentSession(
    val id: String = UUID.randomUUID().toString(),
    val title: String = "",

    val titleAutoGenerated: Boolean = true,

    val messages: List<AgentMessage> = emptyList(),
    val config: SessionConfig = SessionConfig(),

    val planSlugs: List<String> = emptyList(),

    val pinned: Boolean = false,
    val createdAt: Long = System.currentTimeMillis(),
    val updatedAt: Long = System.currentTimeMillis()
)

data class SessionConfig(
    val textModelId: String? = null,
    val imageModelId: String? = null,
    val temperature: Float = 0.7f,
    val maxTurns: Int = 24,

    val customRules: List<String> = emptyList(),

    val contextAppIds: List<Long> = emptyList(),
    val contextModuleIds: List<String> = emptyList(),

    val builtApks: List<PersistedApk> = emptyList()
) {
    
    val builtApksSafe: List<PersistedApk>
        get() = @Suppress("USELESS_CAST") (builtApks as? List<PersistedApk>) ?: emptyList()

    
    val contextAppIdsSafe: List<Long>
        get() = @Suppress("USELESS_CAST") (contextAppIds as? List<Long>) ?: emptyList()

    
    val contextModuleIdsSafe: List<String>
        get() = @Suppress("USELESS_CAST") (contextModuleIds as? List<String>) ?: emptyList()
}






data class PersistedApk(
    val appId: Long,
    val apkName: String,
    val apkPath: String,
    val sizeBytes: Long,
    val buildMode: String,
    val packageName: String? = null,
    val versionName: String? = null
)

data class AgentMessage(
    val id: String = UUID.randomUUID().toString(),
    val role: Role,
    val content: String,
    val thinking: String? = null,

    val thinkingSegments: List<ThinkingSegmentData> = emptyList(),

    val thinkingDurationMs: Long? = null,
    val toolCalls: List<RecordedToolCall> = emptyList(),

    val producedFiles: List<String> = emptyList(),

    val attachments: List<String> = emptyList(),

    val userAttachments: List<UserAttachment> = emptyList(),

    val mentionedFiles: List<String> = emptyList(),
    val isError: Boolean = false,
    val timestamp: Long = System.currentTimeMillis()
) {
    enum class Role { USER, ASSISTANT, SYSTEM }

    




    val userAttachmentsSafe: List<UserAttachment>
        get() = @Suppress("USELESS_CAST") (userAttachments as? List<UserAttachment>) ?: emptyList()

    




    val thinkingSegmentsSafe: List<ThinkingSegmentData>
        get() = @Suppress("USELESS_CAST") (thinkingSegments as? List<ThinkingSegmentData>) ?: emptyList()
}












data class UserAttachment(
    val path: String,
    val displayName: String,
    val mimeType: String,
    val isImage: Boolean,
    val sizeBytes: Long = 0,
    val entryCount: Int = 0
)

data class RecordedToolCall(
    val toolCallId: String,
    val name: String,
    val argumentsJson: String,
    val resultPreview: String,
    val ok: Boolean,

    val activity: String? = null,

    



    val thoughtSignature: String? = null
) {
    companion object {

        const val RUNNING_SENTINEL = "__running__"
    }
}







data class ThinkingSegmentData(
    val id: String,
    val content: String,
    val durationMs: Long? = null
)
